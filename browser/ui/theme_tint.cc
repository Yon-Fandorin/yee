#include "chrome/browser/ui/views/yee/theme_tint.h"

#include "chrome/browser/profiles/profile.h"
#include "chrome/browser/themes/theme_service.h"
#include "chrome/browser/themes/theme_service_factory.h"
#include "content/public/browser/web_contents.h"
#include "ui/color/color_id.h"
#include "ui/color/color_provider.h"

namespace yee {
std::optional<SkColor> ResolveThemeAccent(content::WebContents& contents) {
  auto* service = ThemeServiceFactory::GetForProfile(
      Profile::FromBrowserContext(contents.GetBrowserContext()));
  if (service->GetIsGrayscale() ||
      (!service->GetUserColor().has_value() &&
       !service->UsingAutogeneratedTheme() && !service->UsingExtensionTheme() &&
       !service->UsingPolicyTheme())) {
    return std::nullopt;
  }
  return contents.GetColorProvider().GetColor(ui::kColorSysPrimary);
}
}  // namespace yee
